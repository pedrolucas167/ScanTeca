import { prisma } from "@/lib/prisma";

export async function exportAccountData(userId: string) {
  // Projeções explícitas. Relações de outras contas, chaves de push e tokens
  // de compartilhamento ficam fora do arquivo.
  const where = { userId };
  const [
    cidade,
    perfil,
    termos,
    preferenciasBiblioteca,
    colecoes,
    livros,
    resenhas,
    registrosLeitura,
    sessoesLeitura,
    diario,
    anotacoes,
    conversasOraculo,
    mensagensOraculo,
    resultadosOraculo,
    feedbackRecomendacoes,
    publicacoes,
    comentarios,
    reacoes,
    favoritos,
    participacoesClubes,
    discussoesClubes,
    respostasClubes,
    discussoesLivros,
    respostasLivros,
    preferenciasNotificacoes,
    dispositivos,
    denunciasEnviadas,
    notificacoesRecebidas,
    contasSeguidas,
    seguidores,
    bloqueiosFeitos,
  ] = await prisma.$transaction([
    prisma.privacyPreference.findUnique({ where, select: { city: true } }),
    prisma.socialProfile.findUnique({ where, select: { displayName: true, bio: true, visibility: true, createdAt: true, updatedAt: true } }),
    prisma.termsAcceptance.findMany({ where, select: { version: true, acceptedAt: true } }),
    prisma.librarySetting.findUnique({ where, select: { name: true, shareEnabled: true, oracleProfile: true, oracleMemoryEnabled: true, yearlyGoal: true, accentTheme: true } }),
    prisma.collection.findMany({ where, select: { id: true, name: true, createdAt: true } }),
    prisma.book.findMany({ where, select: { id: true, isbn: true, title: true, author: true, publishedDate: true, synopsis: true, status: true, collectionId: true, notes: true, rating: true, genre: true, pages: true, currentPage: true, startedAt: true, finishedAt: true, customOrder: true, readCount: true, reclubeCount: true, reclubeStartedAt: true, createdAt: true, updatedAt: true } }),
    prisma.review.findMany({ where, select: { id: true, bookId: true, content: true, rating: true, createdAt: true, updatedAt: true } }),
    prisma.readingLog.findMany({ where, select: { id: true, bookId: true, date: true, pages: true, note: true, createdAt: true } }),
    prisma.readingSession.findMany({ where, select: { id: true, bookId: true, startedPage: true, currentPage: true, startedAt: true, endedAt: true, durationSec: true, createdAt: true, updatedAt: true } }),
    prisma.diaryEntry.findMany({ where, select: { id: true, bookId: true, sessionId: true, type: true, content: true, page: true, tags: true, ragEnabled: true, createdAt: true, updatedAt: true } }),
    prisma.annotation.findMany({ where, select: { id: true, passageId: true, content: true, position: true, type: true, sessionId: true, createdAt: true, updatedAt: true } }),
    prisma.oracleSession.findMany({ where, select: { id: true, title: true, mode: true, createdAt: true, updatedAt: true } }),
    prisma.oracleMessage.findMany({ where, select: { id: true, sessionId: true, role: true, content: true, createdAt: true } }),
    prisma.oracleArtifact.findMany({ where, select: { id: true, sessionId: true, type: true, title: true, content: true, createdAt: true, updatedAt: true } }),
    prisma.recommendationFeedback.findMany({ where, select: { id: true, title: true, author: true, kind: true, source: true, createdAt: true, updatedAt: true } }),
    prisma.feedPost.findMany({ where, select: { id: true, content: true, label: true, imageUrl: true, moderationStatus: true, moderatedAt: true, createdAt: true, updatedAt: true } }),
    prisma.feedComment.findMany({ where, select: { id: true, content: true, createdAt: true, updatedAt: true } }),
    prisma.feedReaction.findMany({ where, select: { createdAt: true } }),
    prisma.feedBookmark.findMany({ where, select: { createdAt: true } }),
    prisma.bookClubMember.findMany({ where, select: { role: true, joinedAt: true } }),
    prisma.bookClubDiscussion.findMany({ where, select: { id: true, title: true, content: true, createdAt: true, updatedAt: true } }),
    prisma.bookClubDiscussionReply.findMany({ where, select: { id: true, content: true, createdAt: true, updatedAt: true } }),
    prisma.bookDiscussion.findMany({ where, select: { id: true, title: true, content: true, quote: true, createdAt: true, updatedAt: true } }),
    prisma.bookDiscussionReply.findMany({ where, select: { id: true, content: true, quote: true, createdAt: true } }),
    prisma.notificationPreference.findUnique({ where, select: { reviews: true, updates: true, progress: true, createdAt: true, updatedAt: true } }),
    prisma.pushSubscription.findMany({ where, select: { createdAt: true, updatedAt: true } }),
    prisma.socialReport.findMany({ where: { reporterId: userId }, select: { reason: true, details: true, status: true, createdAt: true, updatedAt: true } }),
    prisma.socialNotification.findMany({ where: { recipientId: userId }, select: { type: true, readAt: true, createdAt: true } }),
    prisma.socialFollow.findMany({ where: { followerId: userId }, select: { createdAt: true } }),
    prisma.socialFollow.findMany({ where: { followingId: userId }, select: { createdAt: true } }),
    prisma.socialBlock.findMany({ where: { blockerId: userId }, select: { createdAt: true } }),
  ]);
  return {
    cidade,
    perfil,
    termos,
    preferenciasBiblioteca,
    colecoes,
    livros,
    resenhas,
    registrosLeitura,
    sessoesLeitura,
    diario,
    anotacoes,
    conversasOraculo,
    mensagensOraculo,
    resultadosOraculo,
    feedbackRecomendacoes,
    publicacoes,
    comentarios,
    reacoes,
    favoritos,
    participacoesClubes,
    discussoesClubes,
    respostasClubes,
    discussoesLivros,
    respostasLivros,
    preferenciasNotificacoes,
    dispositivos,
    denunciasEnviadas,
    notificacoesRecebidas,
    contasSeguidas,
    seguidores,
    bloqueiosFeitos,
  };
}
